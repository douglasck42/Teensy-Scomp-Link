// ===== CORE FUNCTIONS =====

void drawSprite(LedStrip &s, const uint32_t sprite[8][8], int offset) {
  int index = offset;

  for (int y = 0; y < 8; y++) {
    for (int x = 0; x < 8; x++) {
      uint32_t hex = pgm_read_dword(&sprite[y][x]);
      s.strip.setPixelColor(index++, hexColor(s, hex));
    }
  }
}

void clearStrip(LedStrip &s) {
  for (int i = 0; i < s.strip.numPixels(); i++) {
    s.strip.setPixelColor(i, 0);
  }
}

