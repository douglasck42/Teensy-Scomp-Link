void show_all_sprites(LedStrip &s, uint16_t time_delay, uint16_t ani_delay, uint8_t ani_repeat) {
  drawSprite(s, SPRITE_STITCH);
  s.strip.show();
  delay(time_delay*3);

  drawSprite(s, SPRITE_BLUEBALL);
  s.strip.show();
  delay(time_delay*2);

  for (uint8_t i = 0; i < ani_repeat; i++) {
    drawSprite(s, SPRITE_FIREWORK_ORANGE_1);
    s.strip.show();
    delay(ani_delay);
    drawSprite(s, SPRITE_FIREWORK_ORANGE_2);
    s.strip.show();
    delay(ani_delay);
  }

  drawSprite(s, SPRITE_BONES);
  s.strip.show();
  delay(time_delay);

  drawSprite(s, SPRITE_HEART_FANCY);
  s.strip.show();
  delay(time_delay);

  drawSprite(s, SPRITE_SMILEY);
  s.strip.show();
  delay(time_delay);

  drawSprite(s, SPRITE_HEART);
  s.strip.show();
  delay(time_delay);

}
